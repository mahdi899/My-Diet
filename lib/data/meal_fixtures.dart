Meal enrichDemoMeal(Meal meal) {
  final recipe = _recipes[meal.title];
  final ingredients = meal.amount.split('\n').map((line) {
    final split = line.indexOf(':');
    final name = split < 0 ? line : line.substring(0, split).trim();
    var portion = split < 0 ? '' : line.substring(split + 1).trim();
    const digits = '۰۱۲۳۴۵۶۷۸۹';
    portion = portion.replaceAllMapped(
      RegExp('[۰-۹]'),
      (m) => '${digits.indexOf(m[0]!)}',
    );
    portion = portion
        .replaceFirst('سه‌چهارم', '0.75')
        .replaceFirst('نصف', '0.5');
    final number = RegExp(r'^(\d+(?:\.\d+)?)\s*(.+)$').firstMatch(portion);
    // Keep the complete stated unit, including parenthetical equivalents. No conversions.
    return MealIngredient(
      name,
      name,
      number == null ? null : double.tryParse(number[1]!),
      number?[2] ?? portion,
      basis: name.contains('پخته') || name.contains('آب‌پز')
          ? 'پخته'
          : name.contains('خشک') || name.contains('خام')
          ? 'خام'
          : 'مطابق مقدار درج‌شده',
    );
  }).toList();
  // Optional seasoning is an explicit fixture quantity, not a nutritional conversion.
  final requiredIngredients = ingredients
      .where((i) => !i.unit.contains('دلخواه'))
      .toList();
  return meal.copyWith(
    preparationMinutes: recipe?.$1,
    instructions: recipe?.$2 ?? '',
    quantityBasis:
        'وزن‌های دارای برچسب پخته پس از پخت و موارد خشک یا خام پیش از پخت اندازه‌گیری می‌شوند؛ زمان آماده‌سازی از مواد ازپیش‌پخته محاسبه شده است.',
    ingredients: requiredIngredients,
  );
}
