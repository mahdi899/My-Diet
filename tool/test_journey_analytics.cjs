const assert = require('node:assert/strict');
const { readFileSync } = require('node:fs');
const { runInNewContext } = require('node:vm');
const { resolve } = require('node:path');
const sandbox = { Intl };
runInNewContext(readFileSync(resolve(__dirname, '../admin/journey-analytics.js'), 'utf8'), sandbox);
const { sessions, journeyReport } = sandbox.SabzineJourneys;
const range = { from: '2026-10-01', to: '2026-10-31', platform: 'all', appVersion: 'all' };
const first = journeyReport(sessions, { ...range, sessionType: 'first_visit' });
assert.equal(first.sessions, 4);
assert.equal(first.journeys[0].path, 'home → plan_purchase → questionnaire');
assert.equal(first.journeys[0].count, 2);
assert.equal(first.edges.find(edge => edge.fromScreenId === 'home' && edge.toScreenId === 'plan_purchase').percent, 75);
const homeActive = first.active.find(row => row.screenId === 'home').milliseconds;
assert.equal(homeActive, 8000 + 6000 + 5000 + 4000);
const returning = journeyReport(sessions, { ...range, sessionType: 'returning' });
assert.equal(returning.edges.some(edge => edge.toScreenId === 'questionnaire'), false);
assert.equal(returning.edges.find(edge => edge.toScreenId === 'plan_day').count, 2);
const authenticatedLater = sessions.find(item => item.id === 'e');
assert.equal(authenticatedLater.firstAuthenticated, true);
assert.equal(journeyReport([authenticatedLater], { ...range, sessionType: 'first_visit' }).status, 'empty');
const silent = { id: 'silent', date: '2026-10-24', platform: 'android', appVersion: '1.0.0', sessionType: 'first_visit', firstAuthenticated: false, events: [{ type: 'screen_viewed', screenId: 'home', activeMs: 1000 }, { type: 'screen_viewed', screenId: 'login', activeMs: 1000 }] };
const withoutEdges = journeyReport([silent], { ...range, sessionType: 'first_visit' });
assert.equal(withoutEdges.edges.length, 0);
assert.equal(withoutEdges.journeys[0].path, 'home → login');
assert.equal(journeyReport(sessions, { from: '2026-11-01', to: '2026-11-02', sessionType: 'returning' }).status, 'empty');
assert.equal(journeyReport(sessions, { from: '2026-10-30', to: '2026-10-01', sessionType: 'first_visit' }).status, 'invalid');
console.log('journey analytics passed');
