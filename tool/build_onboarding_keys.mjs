// Generates onboarding/onboarding-keys.js from the canonical onboarding spec, so the web onboarding can send
// stable question keys and option codes with every answer (the server then never has to guess
// from wording). Run from the backend folder:
//   cd backend && node --import tsx ../tool/build_onboarding_keys.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { SPEC_QUESTIONS } from '../backend/src/onboarding/spec.ts';
import { norm } from '../backend/src/onboarding/mapper.ts';

const index = {};
for (const question of SPEC_QUESTIONS) {
  const options = {};
  for (const option of question.options ?? []) options[norm(option.label)] = option.code;
  const entry = { key: question.key, options };
  for (const title of [question.title, ...(question.demoTitles ?? [])]) {
    if (!(norm(title) in index) || (question.demoTitles ?? []).includes(title)) index[norm(title)] = entry;
  }
}

const source = `/* Generated by tool/build_onboarding_keys.mjs from backend/src/onboarding/spec.ts. Do not edit by hand. */
(function (global) {
  var INDEX = ${JSON.stringify(index)};
  var DIGITS = { '۰': '0', '۱': '1', '۲': '2', '۳': '3', '۴': '4', '۵': '5', '۶': '6', '۷': '7', '۸': '8', '۹': '9', '٠': '0', '١': '1', '٢': '2', '٣': '3', '٤': '4', '٥': '5', '٦': '6', '٧': '7', '٨': '8', '٩': '9' };
  function norm(value) {
    return String(value)
      .replace(/[۰-۹٠-٩]/g, function (d) { return DIGITS[d] || d; })
      .replace(/[ي]/g, 'ی')
      .replace(/[ك]/g, 'ک')
      .replace(/[\\u200c\\u200f\\u200e]/g, '')
      .replace(/[؟?!.،,:؛]/g, '')
      .replace(/\\s+/g, ' ')
      .trim()
      .toLowerCase();
  }
  /** Labels the person picked for one demo question, whatever the answer shape is. */
  function pickedLabels(q, a) {
    if (a === undefined || a === null || !q.options) return [];
    if (q.multi && a && Array.isArray(a.choices)) return a.choices.map(function (i) { return q.options[i] && q.options[i].label; }).filter(Boolean);
    if (typeof a === 'object') return a.choice != null && q.options[a.choice] ? [q.options[a.choice].label] : [];
    return q.options[a] ? [q.options[a].label] : [];
  }
  /** { key, codes? } for a demo question and its answer; {} when the question is not part of the spec. */
  function canonical(q, a) {
    var entry = INDEX[norm(q.q)];
    if (!entry) return {};
    var out = { key: entry.key };
    var codes = pickedLabels(q, a).map(function (label) { return entry.options[norm(label)]; }).filter(Boolean);
    if (codes.length) out.codes = codes;
    return out;
  }
  global.SabzineKeys = { canonical: canonical, norm: norm, version: 1 };
})(typeof window !== 'undefined' ? window : globalThis);
`;

const target = fileURLToPath(new URL('../frontend/public/onboarding/onboarding-keys.js', import.meta.url));
writeFileSync(target, source, 'utf8');
console.log(`wrote ${target} (${Object.keys(index).length} titles)`);
