const assert = require('node:assert/strict');
const { readFileSync } = require('node:fs');
const { runInNewContext } = require('node:vm');
const { resolve } = require('node:path');
const sandbox = { structuredClone, Intl };
runInNewContext(readFileSync(resolve(__dirname, '../backend/admin-web/admin-reports.js'), 'utf8'), sandbox);
const reports = sandbox.SabzineReports;
const range = { from: '2026-08-01', to: '2026-10-30', event: 'activity' };
const ready = reports.retentionReport(reports.cohorts, range);
const byId = Object.fromEntries(ready.rows.map(row => [row.id, row]));
assert.equal(ready.status, 'ready');
assert.equal(byId.sep.cells.week1.state, 'measured');
assert.equal(byId.sep.cells.week1.percent, 70);
assert.equal(byId.oct.cells.week1.state, 'measured');
assert.equal(byId.oct.cells.week2.state, 'not_yet_measurable');
assert.equal(byId.oct.cells.week4.state, 'not_yet_measurable');
assert.equal(byId.new.cells.week1.state, 'not_yet_measurable');
assert.equal(byId.quiet.cells.week4.state, 'measured');
assert.equal(byId.quiet.cells.week4.count, 0);
assert.equal(byId.quiet.cells.week4.percent, 0);
const tracking = reports.retentionReport(reports.cohorts, { ...range, event: 'tracking' });
assert.equal(tracking.rows.find(row => row.id === 'sep').cells.week1.count, 22);
assert.equal(reports.retentionReport(reports.cohorts, { from: '2026-11-01', to: '2026-11-02' }).status, 'empty');
assert.equal(reports.retentionReport(reports.cohorts, { from: '2026-10-30', to: '2026-10-01' }).status, 'invalid');
assert.equal(reports.rankFoods(reports.foodEvents, { from: '2026-10-01', to: '2026-10-30', kind: 'disliked' }).rows[0].label, 'سوپ جو');
assert.equal(reports.rankFoods(reports.foodEvents, { from: '2026-10-01', to: '2026-10-30', kind: 'reason' }).rows[0].count, 2);
assert.equal(reports.feedbackSummary({ eligible: 0, submitted: 0, continued: 0 }).status, 'empty');
assert.equal(reports.feedbackSummary(reports.feedbackFixture).participation.percent, 43);
const board = reports.leaderboard(reports.specialists, 'rating');
assert.equal(board.at(-1).ratingAverage, null);
assert.notEqual(board[0].ratingAverage, 0);
assert.equal(reports.leaderboard(reports.specialists, 'response').at(-1).messageResponse, null);
assert.equal(reports.leaderboard([reports.specialists[0]], 'workload').length, 1);
const reasons = [{ id: 'reason-1', label: 'قدیمی', active: true, historicalLabels: [] }];
reports.updateReason(reasons, 'reason-1', { label: 'جدید' });
reports.updateReason(reasons, 'reason-1', { active: false });
assert.equal(reasons[0].id, 'reason-1');
assert.deepEqual(reasons[0].historicalLabels, ['قدیمی']);
assert.equal(reasons[0].active, false);
assert.equal(reasons.length, 1);
const questions = reports.createQuestionnaire();
const saved = questions.submittedPrompt('q-goal');
questions.rename('q-goal', 'هدف جدید');
questions.setActive('q-goal', false);
assert.equal(questions.list()[0].id, 'q-goal');
assert.deepEqual(questions.list()[0].historicalPrompts, ['هدفت از برنامه چیست؟']);
assert.equal(questions.submittedPrompt('q-goal'), saved);
assert.equal(questions.publish(), 2);
console.log('admin reports passed');
